def source_label(src: str) -> str:
    if src in SOURCE_LABELS:
        return SOURCE_LABELS[src]
    if src.startswith("seed_"):
        return f"Посев в канале: {src[5:]}"
    if src.startswith("site_"):
        return f"Лендинг: {src[5:]}"
    return src or "Прямой переход"


